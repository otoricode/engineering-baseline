// header menulis bagian berkas DI ATAS klausa package: penanda mesin plus prosa katalog yang
// menerangkan berkas ini masih boleh ditulis ulang sampai dibekukan.
func (m modul) header(dasar string) string {
	return penandaGenerated + "\n//\n" + cfg.KomentarBlok(m.kat.T("genmodule.komentar.header",
		map[string]string{
			"tag":   m.tag,
			"pkg":   m.pkg,
			"beku":  namaBeku(dasar),
			"gen":   namaBerkas(m.c, dasar),
			"alat":  "genmodule",
			"fitur": m.feature,
		}))
}

// headerRegister menulis SELURUH bagian register.<gen> di atas deklarasi pertamanya: penanda
// generated, prosa headernya, klausa package, dan blok impor.
//
// Ia menerima katalog karena prosa header adalah teks yang ditulis KE DALAM kode proyek target;
// header tanpa prosa akan memindahkan kalimatnya ke tempat yang tidak disentuh uji ini, dan
// itulah kelas cacat yang justru sedang dijaga.
func headerRegister(c cfg.Config, kat cfg.Katalog, tag, pkg, feature string) string {
	m := modul{c: c, kat: kat, tag: tag, pkg: pkg, feature: feature, alias: cfg.AliasGen(pkg)}
	var b strings.Builder
	b.WriteString(m.header("register"))
	fmt.Fprintf(&b, "\npackage %s\n\nimport (\n\t%q\n\t%q\n\n\t%s %q\n)\n", feature,
		impRouter, impORM, m.alias, c.ImportGen(pkg))
	return b.String()
}

func (m modul) register() []byte {
	var b strings.Builder
	b.WriteString(headerRegister(m.c, m.kat, m.tag, m.pkg, m.feature))
	b.WriteString("\n")
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.register", map[string]string{
		"jumlah": fmt.Sprint(len(m.ops)),
		"tag":    m.tag,
		"alias":  m.alias,
		"router": pkgRouter() + "." + tipeRouter,
		"db":     pkgORM() + "." + tipeDB,
	})))
	fmt.Fprintf(&b, "func Register(public, protected *%s.%s, db *%s.%s) {\n\t_ = db\n"+
		"\t%s.Mount(public, protected, &handler{svc: newService(nil)})\n}\n",
		pkgRouter(), tipeRouter, pkgORM(), tipeDB, m.alias)
	return []byte(b.String())
}

func (m modul) repository() []byte {
	var b strings.Builder
	b.WriteString(m.header("repository"))
	fmt.Fprintf(&b, "\npackage %s\n\nimport (\n\t%q\n", m.feature, m.c.ImportAppcontext())
	if m.adaMetaDiMana() {
		fmt.Fprintf(&b, "\t%q\n", m.c.ImportHttpx())
	}
	b.WriteString(")\n\n")
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.store", map[string]string{
		"ctx": m.c.PkgAppcontext() + ".AppContext",
	})))
	b.WriteString("type store interface {\n")
	for i, op := range m.ops {
		if i > 0 {
			b.WriteString("\n")
		}
		if op.rute != "" {
			fmt.Fprintf(&b, "\t// %s\n", op.rute)
		}
		fmt.Fprintf(&b, "\t%s\n", m.tandaTangan(op))
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func (m modul) service() []byte {
	var b strings.Builder
	b.WriteString(m.header("service"))
	fmt.Fprintf(&b, "\npackage %s\n\nimport (\n\t%q\n", m.feature, m.c.ImportAppcontext())
	if m.adaMetaDiMana() {
		fmt.Fprintf(&b, "\t%q\n", m.c.ImportHttpx())
	}
	b.WriteString(")\n\n")
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.service", nil)))
	b.WriteString("type service struct {\n\tstore store\n}\n\n")
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.service_new", nil)))
	b.WriteString("func newService(store store) *service { return &service{store: store} }\n")

	for _, op := range m.ops {
		fmt.Fprintf(&b, "\nfunc (s *service) %s {\n\treturn s.store.%s(%s)\n}\n",
			m.tandaTangan(op), op.nama, m.namaArgumen(op))
	}
	return []byte(b.String())
}

func (m modul) handler() []byte {
	var b strings.Builder
	b.WriteString(m.header("handler"))
	fmt.Fprintf(&b, "\npackage %s\n\nimport (\n\t\"context\"\n\n\t%s %q\n\t%q%s\n)\n\n",
		m.feature, m.alias, m.c.ImportGen(m.pkg), m.c.ImportAppcontext(), m.imporConv())
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.handler", map[string]string{
		"alias": m.alias,
	})))
	b.WriteString("type handler struct{ svc *service }\n\n")
	fmt.Fprintf(&b, "var _ %s.StrictServerInterface = (*handler)(nil)\n\n", m.alias)
	b.WriteString(cfg.KomentarBlok(m.kat.T("genmodule.komentar.handler_ctx", map[string]string{
		"ctx": m.c.PkgAppcontext(),
	})))

	for _, op := range m.ops {
		m.tulisHandler(&b, op)
	}
	return []byte(b.String())
}

func (m modul) tulisHandler(b *strings.Builder, op operasi) {
	fmt.Fprintf(b, "\n%s", cfg.KomentarBlok(m.kat.T("genmodule.komentar.operasi",
		map[string]string{"op": op.nama, "rute": op.rute})))
	fmt.Fprintf(b, "func (h *handler) %s(ctx context.Context, request %s.%sRequestObject) (%s.%sResponseObject, error) {\n",
		op.nama, m.alias, op.nama, m.alias, op.nama)

	args := []string{m.c.PkgAppcontext() + ".From(ctx)"}
	for _, a := range op.argumen {
		args = append(args, a.dariWire)
	}
	panggil := fmt.Sprintf("h.svc.%s(%s)", op.nama, strings.Join(args, ", "))

	if op.hasilWire == "" {
		fmt.Fprintf(b, "\tif err := %s; err != nil {\n\t\treturn nil, err\n\t}\n", panggil)
		fmt.Fprintf(b, "\tvar out %s.%s\n", m.alias, op.respons)
		m.tulisAmplop(b, op)
		b.WriteString("\treturn out, nil\n}\n")
		return
	}

	terima := "data, err :="
	if op.metaTipe != "" {
		terima = "data, pg, err :="
	}
	fmt.Fprintf(b, "\t%s %s\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", terima, panggil)
	fmt.Fprintf(b, "\tvar out %s.%s\n", m.alias, op.respons)
	m.tulisAmplop(b, op)
	if op.hasil.keWire == "" {
		b.WriteString("\tout.Data = data\n")
	} else {
		fmt.Fprintf(b, "\tout.Data = %s\n", fmt.Sprintf(op.hasil.keWire, "data"))
	}
	if op.metaTipe != "" {
		// Penyusunan metaData hidup DI SINI, bukan di store — lihat tandaTangan (B-01).
		fmt.Fprintf(b, "\tout.MetaData = %s{Pagination: %s{Page: pg.Page, Limit: pg.Limit, Total: pg.Total, TotalPages: pg.TotalPages}}\n",
			op.metaTipe, op.metaPag)
	}
	b.WriteString("\treturn out, nil\n}\n")
}

// tulisAmplop mengisi field amplop yang respons ini BENAR-BENAR punya. Kedua field diperiksa
// terpisah: respons 204 tidak punya keduanya, dan tag yang belum opt-in envelope punya Message
// tanpa konstanta Status.
//
// Nilai "Success" sengaja TIDAK dari katalog: ia nilai KABEL yang dibaca klien API, bukan prosa
// untuk pembaca kode. Menerjemahkannya membuat badan respons berubah mengikuti bahasa proyek —
// yaitu kontrak yang berbeda per proyek.
func (m modul) tulisAmplop(b *strings.Builder, op operasi) {
	if op.adaStatus {
		fmt.Fprintf(b, "\tout.Status = %s.%s\n", m.alias, konstStatusSukses)
	}
	if op.adaMessage {
		b.WriteString("\tout.Message = \"Success\"\n")
	}
}

// polaRespons memisahkan nama tipe respons sukses: <Operasi><2xx>[JSON]Response.
var polaRespons = regexp.MustCompile(`^(2\d\d)(JSONResponse|Response)$`)

// namaRespons memilih tipe respons SUKSES sebuah operasi dari tipe yang ada di paket generated:
// status 2xx terkecil, dan pada status yang sama bentuk JSON menang atas bentuk telanjang.
// Mengembalikan "" kalau tak satu pun ada — yang dihentikan pemanggilnya, bukan ditebak.
func namaRespons(op string, tipe map[string]*ast.TypeSpec) string {
	terbaik, kodeTerbaik, jsonTerbaik := "", "", false
	for nama := range tipe {
		sisa, ok := strings.CutPrefix(nama, op)
		if !ok {
			continue
		}
		m := polaRespons.FindStringSubmatch(sisa)
		if m == nil {
			continue
		}
		json := m[2] == "JSONResponse"
		if terbaik == "" || m[1] < kodeTerbaik || (m[1] == kodeTerbaik && json && !jsonTerbaik) {
			terbaik, kodeTerbaik, jsonTerbaik = nama, m[1], json
		}
	}
	return terbaik
}

// tandaTangan menulis "Nama(ctx *<appcontext>.AppContext, ...) (hasil, error)" — sama persis
// untuk store dan service, supaya delegasi service jadi satu baris dan setiap penyimpangan
// antara keduanya jadi galat kompilasi.
//
// # Kenapa paginasi keluar sebagai tipe PLATFORM, bukan tipe generated
//
// Angka paginasi memang hanya diketahui kueri yang menghitungnya, jadi ia HARUS ikut nilai balik
// store. Tapi mengembalikannya dalam tipe GENERATED memaksa lapis kueri dan lapis layanan
// mengimpor paket generated — dan B-01 justru melarang itu: tipe kabel berhenti di handler,
// karena mengetik lapis akses data dengan tipe kontrak HTTP membalik rantai sumber kebenaran.
//
// Tipe paginasi platform punya field yang sama persis dengan Pagination generated, dan lapis
// kueri sudah mengimpor paket platform itu untuk hal lain. Handler yang menyusun metaData dari
// nilai itu — satu baris, di satu-satunya lapis yang memang boleh menyebut tipe generated.
func (m modul) tandaTangan(op operasi) string {
	params := []string{"ctx *" + m.c.PkgAppcontext() + ".AppContext"}
	for _, a := range op.argumen {
		params = append(params, a.nama+" "+a.tipe)
	}
	var hasil []string
	if op.hasilWire != "" {
		hasil = append(hasil, op.hasil.tipeInternal)
	}
	if op.metaTipe != "" {
		hasil = append(hasil, m.c.PkgHttpx()+".Pagination")
	}
	hasil = append(hasil, "error")

	ret := hasil[0]
	if len(hasil) > 1 {
		ret = "(" + strings.Join(hasil, ", ") + ")"
	}
	return fmt.Sprintf("%s(%s) %s", op.nama, strings.Join(params, ", "), ret)
}

func (m modul) namaArgumen(op operasi) string {
	out := []string{"ctx"}
	for _, a := range op.argumen {
		out = append(out, a.nama)
	}
	return strings.Join(out, ", ")
}

// imporConv memancarkan baris impor paket konversi HANYA bila ada operasi yang benar-benar
// memanggilnya. Modul yang seluruh Data-nya bertipe tunggal tidak menyentuh satu pun pembantu
// pemetaan, dan impor tak-terpakai adalah GALAT kompilasi di Go — bukan peringatan.
func (m modul) imporConv() string {
	awalan := m.c.PkgDtoconv() + "."
	for _, op := range m.ops {
		if strings.Contains(op.hasil.keWire, awalan) {
			return fmt.Sprintf("\n\t%q", m.c.ImportDtoconv())
		}
		for _, a := range op.argumen {
			if strings.Contains(a.dariWire, awalan) {
				return fmt.Sprintf("\n\t%q", m.c.ImportDtoconv())
			}
		}
	}
	return ""
}

// adaMetaDiMana melaporkan apakah ADA operasi yang membawa metaData WAJIB — hanya itu yang
// membuat lapis kueri dan lapis layanan perlu mengimpor paket platform paginasi. Impor
// tak-terpakai adalah GALAT kompilasi di Go, jadi impornya kondisional.
//
// MetaData sengaja TIDAK dicerminkan gendto: ia amplop, bukan payload, dan Pagination di
// dalamnya satu tipe yang SAMA di seluruh tag. Mencerminkannya per-fitur akan melahirkan
// salinan tipe amplop yang justru dihindari envelope bersama.
func (m modul) adaMetaDiMana() bool {
	for _, op := range m.ops {
		if op.metaTipe != "" {
			return true
		}
	}
	return false
}

// checklistTenancy memancarkan daftar periksa lintas-penyewa untuk metode store berbentuk
// `(ctx)` atau `(ctx, <string>)` — bentuk baca dan lookup by-ID.
//
// Hanya kedua bentuk itu, dan itu batasan sadar: metode bermuatan (create/update) menulis baris
// saat dijalankan, jadi menjalankannya di uji tanpa penyiapan bukan hal yang bisa
// digeneralisasi. Bentuk `(ctx, id)` justru KELAS YANG PALING SERING BOCOR — id telanjang dari
// path, langsung ke DB, tanpa predikat penyewa (T-02).
//
// # Kenapa PROSA, bukan berkas uji Go yang bisa disalin
//
// Sumber alat ini memancarkan kerangka uji Go yang lengkap. Kerangka itu menyebut tipe store
// konkret, konstruktor konteks penyewa, driver basis data, dan pustaka assertion PROYEK ASALNYA
// — empat API yang standar ini tidak menyatakan dan karena itu tidak bisa mengarangnya. Berkas
// Go yang mengarang API menghasilkan uji yang tidak kompilasi di setiap proyek kecuali satu, dan
// yang menyalinnya akan menyimpulkan alat ini rusak, lalu membuang seluruh berkasnya — termasuk
// bagian yang benar.
//
// Yang bertahan portabel adalah KEWAJIBANNYA: metode mana yang harus diuji, apa yang harus
// di-assert, dan kenapa uji berbasis store tiruan tidak bisa menangkap kelas ini sama sekali.
//
// Mengembalikan nil kalau tak ada metode yang cocok — berkas kosong yang terlihat seperti "sudah
// ditangani" lebih buruk daripada tidak ada berkas.
func (m modul) checklistTenancy() []byte {
	var metode []string
	for _, op := range m.ops {
		bentuk := ""
		switch {
		case len(op.argumen) == 0:
			bentuk = "(ctx)"
		case len(op.argumen) == 1 && op.argumen[0].tipe == "string":
			bentuk = "(ctx, " + op.argumen[0].nama + " string)"
		default:
			continue
		}
		metode = append(metode, m.kat.T("genmodule.tenancy.metode", map[string]string{
			"metode": op.nama,
			"bentuk": bentuk,
			"rute":   op.rute,
		}))
	}
	if len(metode) == 0 {
		return nil
	}
	return []byte(m.kat.T("genmodule.tenancy.checklist", map[string]string{
		"tag":    m.tag,
		"fitur":  m.feature,
		"metode": strings.Join(metode, "\n"),
	}) + "\n")
}

// ── Tulis & bekukan ───────────────────────────────────────────────────────────

func tulisModul(m modul, tujuan string, apply bool, keluar, galat io.Writer) int {
	isi := map[string][]byte{
		"register":   m.register(),
		"handler":    m.handler(),
		"service":    m.service(),
		"repository": m.repository(),
	}

	fmt.Fprintln(keluar, m.kat.T("genmodule.baris_modul", map[string]string{
		"tag":     m.tag,
		"fitur":   m.feature,
		"jumlah":  fmt.Sprint(len(m.ops)),
		"tujuan":  tujuan,
		"berkas1": namaBerkas(m.c, berkasKerangka[0]),
	}))

	type keluaran struct {
		nama string
		src  []byte
	}
	var akanDitulis []keluaran

	for _, dasar := range berkasKerangka {
		nama := namaBerkas(m.c, dasar)
		src, err := format.Source(isi[dasar])
		if err != nil {
			// Keluaran yang tidak bisa diformat = keluaran yang tidak kompilasi. Cetak mentahnya
			// supaya kegagalannya bisa didiagnosis, dan JANGAN tulis ke disk.
			fmt.Fprintf(galat, "\n--- %s ---\n%s\n", nama, isi[dasar])
			fmt.Fprintln(galat, m.kat.T("genmodule.gagal_format",
				map[string]string{"berkas": nama, "sebab": err.Error()}))
			return 2
		}
		fmt.Fprintln(keluar, m.kat.T("genmodule.baris_berkas", map[string]string{
			"berkas": nama,
			"baris":  fmt.Sprint(bytes.Count(src, []byte("\n"))),
		}))
		akanDitulis = append(akanDitulis, keluaran{nama, src})
	}

	// Daftar periksa lintas-penyewa (T-01) — berkas KELIMA, dan sengaja BUKAN kode.
	if mentah := m.checklistTenancy(); mentah != nil {
		fmt.Fprintln(keluar, m.kat.T("genmodule.baris_checklist", map[string]string{
			"berkas": namaChecklistTenancy,
			"baris":  fmt.Sprint(bytes.Count(mentah, []byte("\n"))),
		}))
		akanDitulis = append(akanDitulis, keluaran{namaChecklistTenancy, mentah})
	}

	if !apply {
		// Dry-run: nol tulisan, termasuk nol direktori yang dibuat. Sumber alat ini membuat
		// direktori -out SEBELUM memeriksa -apply, jadi "melaporkan saja" tetap menyentuh disk.
		fmt.Fprintln(keluar, m.kat.T("gen.dry_run", map[string]string{"jumlah": fmt.Sprint(len(akanDitulis))}))
		return 0
	}
	if err := os.MkdirAll(tujuan, 0o755); err != nil {
		fmt.Fprintln(galat, m.kat.T("genmodule.gagal_buat_dir",
			map[string]string{"jalur": tujuan, "sebab": err.Error()}))
		return 2
	}
	for _, k := range akanDitulis {
		jalur := filepath.Join(tujuan, k.nama)
		if err := os.WriteFile(jalur, k.src, 0o644); err != nil {
			fmt.Fprintln(galat, m.kat.T("genmodule.gagal_tulis",
				map[string]string{"jalur": jalur, "sebab": err.Error()}))
			return 2
		}
	}
	return 0
}

// bekukan mengakhiri masa regenerasi sebuah modul: `<dasar><genSuffix>` -> `<dasar>.go`, header
// generator dilucuti.
//
// Sesudah ini generator MENOLAK menyentuh modulnya (deteksi lewat nama berkas), dan itulah
// intinya — yang membekukan bukan catatan di suatu daftar melainkan keadaan direktori itu
// sendiri, yang tidak bisa menyimpang dari kenyataan.
func bekukan(c cfg.Config, kat cfg.Katalog, akar, dirFitur, feat string, apply bool,
	keluar, galat io.Writer) int {

	nama, err := namaDiDirektori(dirFitur)
	if err != nil {
		fmt.Fprintln(galat, kat.T("genmodule.gagal_tulis",
			map[string]string{"jalur": dirFitur, "sebab": err.Error()}))
		return 2
	}
	ada := map[string]bool{}
	for _, n := range nama {
		ada[n] = true
	}

	var dasarAda []string
	for _, dasar := range berkasKerangka {
		if ada[namaBerkas(c, dasar)] {
			dasarAda = append(dasarAda, dasar)
		}
	}
	if len(dasarAda) == 0 {
		fmt.Fprintln(galat, kat.T("genmodule.beku_tanpa_gen",
			map[string]string{"jalur": dirFitur, "sufiks": c.Go.GenSuffix}))
		return 2
	}
	// Tabrakan diperiksa untuk SELURUH berkas sebelum satu pun disentuh: berhenti di tengah
	// meninggalkan modul separuh beku, yang tidak terbaca sebagai keadaan mana pun.
	for _, dasar := range dasarAda {
		if ada[namaBeku(dasar)] {
			fmt.Fprintln(galat, kat.T("genmodule.beku_tabrakan",
				map[string]string{"jalur": filepath.Join(dirFitur, namaBeku(dasar))}))
			return 2
		}
	}

	fmt.Fprintln(keluar, kat.T("genmodule.beku_judul", map[string]string{"jalur": dirFitur}))
	for _, dasar := range dasarAda {
		fmt.Fprintln(keluar, kat.T("genmodule.beku_baris", map[string]string{
			"dari": namaBerkas(c, dasar), "jadi": namaBeku(dasar),
		}))
		if !apply {
			continue
		}
		lama := filepath.Join(dirFitur, namaBerkas(c, dasar))
		src, err := os.ReadFile(lama)
		if err != nil {
			fmt.Fprintln(galat, kat.T("genmodule.gagal_tulis",
				map[string]string{"jalur": lama, "sebab": err.Error()}))
			return 2
		}
		baru := filepath.Join(dirFitur, namaBeku(dasar))
		if err := os.WriteFile(baru, lucutiHeader(src), 0o644); err != nil {
			fmt.Fprintln(galat, kat.T("genmodule.gagal_tulis",
				map[string]string{"jalur": baru, "sebab": err.Error()}))
			return 2
		}
		if err := os.Remove(lama); err != nil {
			fmt.Fprintln(galat, kat.T("genmodule.gagal_tulis",
				map[string]string{"jalur": lama, "sebab": err.Error()}))
			return 2
		}
	}
	if apply {
		fmt.Fprintln(keluar, kat.T("genmodule.beku_sesudah", map[string]string{
			"fitur": feat, "jalur": c.JalurLedgerModul(akar),
		}))
		return 0
	}
	fmt.Fprintln(keluar, kat.T("gen.dry_run", map[string]string{"jumlah": fmt.Sprint(len(dasarAda))}))
	return 0
}

// lucutiHeader membuang blok header generator dari awal berkas. Header itu BERBOHONG sesudah
// pembekuan: berkasnya justru DIMAKSUDKAN untuk disunting sejak saat itu, dan "DO NOT EDIT" yang
// tertinggal akan membuat pembaca berikutnya ragu menyentuh berkas yang memang miliknya.
func lucutiHeader(src []byte) []byte {
	i := bytes.Index(src, []byte("\npackage "))
	if i < 0 {
		return src
	}
	return bytes.TrimLeft(src[i+1:], "\n")
}
