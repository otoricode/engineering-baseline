// jalankan adalah seluruh alat sebagai fungsi murni-cukup untuk diuji: argumen masuk, dua aliran
// keluar, satu kode keluar. main() tidak boleh punya perilaku yang tak bisa disentuh uji.
func jalankan(argv []string, keluar, galat io.Writer) int {
	praConfig, praPesan, bantuan := cfg.PraPindai(argv, benderaBernilai)

	// Bantuan dijawab SEBELUM config dimuat. Alat yang tak bisa menjelaskan dirinya sendiri
	// sebelum dikonfigurasi memaksa orang menebak bendera apa yang ada — dan yang pertama
	// menabraknya adalah orang yang baru memasang paket ini, yang belum punya config.
	if bantuan {
		return cetakBantuan(keluar, galat, praConfig, praPesan)
	}

	c, akar, err := cfg.MuatDari(praConfig)
	if err != nil {
		cfg.LaporGagalConfig(galat, praPesan, err)
		return 2
	}

	kat, err := cfg.MuatKatalogUntuk(praPesan, c.Language)
	if err != nil {
		fmt.Fprintf(galat, cfg.BootstrapKatalog+"\n", err)
		return 2
	}
	if err := kat.Lengkap(kunciDipakai); err != nil {
		fmt.Fprintf(galat, cfg.BootstrapKatalog+"\n", err)
		return 2
	}

	var o opsi
	fs := flag.NewFlagSet("genmodule", flag.ContinueOnError)
	fs.SetOutput(galat)
	daftarBendera(fs, &o, kat)
	if err := fs.Parse(argv); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}

	return kerjakan(c, akar, o, kat, keluar, galat)
}

func daftarBendera(fs *flag.FlagSet, o *opsi, kat cfg.Katalog) {
	fs.StringVar(&o.config, "config", "", kat.T("genmodule.bendera.config", nil))
	fs.StringVar(&o.messages, "messages", "", kat.T("genmodule.bendera.messages", nil))
	fs.StringVar(&o.tag, "tag", "", kat.T("genmodule.bendera.tag", nil))
	fs.StringVar(&o.pkg, "pkg", "", kat.T("genmodule.bendera.pkg", nil))
	fs.StringVar(&o.feature, "feature", "", kat.T("genmodule.bendera.feature", nil))
	fs.StringVar(&o.out, "out", "", kat.T("genmodule.bendera.out", nil))
	fs.BoolVar(&o.apply, "apply", false, kat.T("genmodule.bendera.apply", nil))
	fs.BoolVar(&o.force, "force", false, kat.T("genmodule.bendera.force", nil))
	fs.BoolVar(&o.freeze, "freeze", false, kat.T("genmodule.bendera.freeze", nil))
}

// cetakBantuan menjawab -h tanpa menuntut config. Kalau config KEBETULAN ketemu, bantuan dicetak
// dalam bahasa proyek itu; kalau tidak, dalam seluruh bahasa katalog — alat yang belum
// dikonfigurasi tidak tahu bahasa siapa yang benar, dan menebak salah satu sama buruknya dengan
// diam.
func cetakBantuan(keluar, galat io.Writer, praConfig, dirPesan string) int {
	bahasa := cfg.BahasaKatalog
	if c, _, err := cfg.MuatDari(praConfig); err == nil && c.Language != "" {
		bahasa = []string{c.Language}
	}
	dicetak := false
	var gagal error
	for _, b := range bahasa {
		kat, err := cfg.MuatKatalogUntuk(dirPesan, b)
		if err != nil {
			if gagal == nil {
				gagal = err
			}
			continue
		}
		if dicetak {
			fmt.Fprintln(keluar)
		}
		var o opsi
		fs := flag.NewFlagSet("genmodule", flag.ContinueOnError)
		fs.SetOutput(keluar)
		daftarBendera(fs, &o, kat)
		fmt.Fprintln(keluar, kat.T("genmodule.pemakaian", nil))
		fs.PrintDefaults()
		dicetak = true
	}
	if !dicetak {
		// Bantuan pun butuh katalog, karena teks tiap bendera ada di sana. Yang dilaporkan harus
		// SEBABNYA (katalog mana yang tak terbaca), bukan bendera yang diminta.
		fmt.Fprintf(galat, cfg.BootstrapKatalog+"\n", gagal)
		return 2
	}
	return 0
}

// ── Nama berkas dan keadaan beku ──────────────────────────────────────────────

// namaBerkas memberi nama berkas kerangka dalam keadaan TERGENERATE.
func namaBerkas(c cfg.Config, dasar string) string { return c.NamaBerkasGen(dasar) }

// namaBeku memberi nama berkas kerangka SESUDAH pembekuan. `.go` bukan nilai config: berkas Go
// yang tidak berakhiran `.go` tidak dikompilasi sama sekali.
func namaBeku(dasar string) string { return dasar + ".go" }

// sudahBeku membaca keadaan modul dari NAMA BERKAS di direktorinya, bukan dari sebuah daftar.
// Daftar bisa menyimpang dari kenyataan; nama berkas tidak bisa.
func sudahBeku(namaDiDirektori []string, c cfg.Config) bool {
	return len(berkasBeku(namaDiDirektori, c)) > 0
}

// berkasBeku melaporkan berkas kerangka mana yang sudah tanpa sufiks generated — bukti bahwa
// modulnya sudah dikawinkan tangan, dan sekaligus isi pesan penolakannya.
func berkasBeku(namaDiDirektori []string, c cfg.Config) []string {
	ada := map[string]bool{}
	for _, n := range namaDiDirektori {
		ada[n] = true
	}
	var out []string
	for _, dasar := range berkasKerangka {
		n := namaBeku(dasar)
		if n != namaBerkas(c, dasar) && ada[n] {
			out = append(out, n)
		}
	}
	return out
}

// periksaSufiks menolak genSuffix yang membuat nama tergenerate dan nama beku IDENTIK (mis.
// `.go` polos). Tanpa penjaga ini, `sudahBeku` tak akan pernah benar dan `-freeze` akan menimpa
// berkasnya sendiri — seluruh mekanisme pembekuan mati TANPA satu pesan pun. Tiap jalur
// "lewati kasus ini" adalah jalur di mana pemeriksaan tidak berjalan; jadi kasus ini tidak
// dilewati, ia dihentikan.
func periksaSufiks(c cfg.Config, kat cfg.Katalog) error {
	for _, dasar := range berkasKerangka {
		if namaBerkas(c, dasar) == namaBeku(dasar) {
			return errors.New(kat.T("genmodule.sufiks_menabrak_beku",
				map[string]string{"sufiks": c.Go.GenSuffix, "berkas": namaBeku(dasar)}))
		}
	}
	return nil
}

// namaDiDirektori mengembalikan nama berkas di sebuah direktori. Direktori yang belum ada bukan
// galat — itu justru keadaan modul yang baru pertama kali dibangkitkan.
func namaDiDirektori(dir string) ([]string, error) {
	entri, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	out := make([]string, 0, len(entri))
	for _, e := range entri {
		if !e.IsDir() {
			out = append(out, e.Name())
		}
	}
	return out, nil
}

// ── Alur ──────────────────────────────────────────────────────────────────────

func kerjakan(c cfg.Config, akar string, o opsi, kat cfg.Katalog, keluar, galat io.Writer) int {
	if err := periksaSufiks(c, kat); err != nil {
		fmt.Fprintln(galat, err)
		return 2
	}
	if o.pkg == "" {
		fmt.Fprintln(galat, kat.T("genmodule.pkg_wajib", nil))
		return 2
	}
	feat := o.feature
	if feat == "" {
		feat = o.pkg
	}
	dirFitur := filepath.Join(c.DirFeature(akar), feat)

	if o.freeze {
		return bekukan(c, kat, akar, dirFitur, feat, o.apply, keluar, galat)
	}
	if o.tag == "" {
		fmt.Fprintln(galat, kat.T("genmodule.tag_wajib", nil))
		return 2
	}

	nama, err := namaDiDirektori(dirFitur)
	if err != nil {
		fmt.Fprintln(galat, kat.T("genmodule.gagal_tulis",
			map[string]string{"jalur": dirFitur, "sebab": err.Error()}))
		return 2
	}
	if beku := berkasBeku(nama, c); len(beku) > 0 && !o.force {
		fmt.Fprintln(galat, kat.T("gen.modul_beku", map[string]string{"pkg": feat}))
		fmt.Fprintln(galat, kat.T("genmodule.kawin_tangan",
			map[string]string{"fitur": feat, "berkas": strings.Join(beku, ", ")}))
		return 2
	}

	tujuan := dirFitur
	if o.out != "" {
		tujuan = o.out
	}

	m, err := baca(c, kat, akar, o.tag, o.pkg, feat)
	if err != nil {
		fmt.Fprintln(galat, err)
		return 2
	}
	return tulisModul(m, tujuan, o.apply, keluar, galat)
}

