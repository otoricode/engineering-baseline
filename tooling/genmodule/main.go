// Alat genmodule — bangkitkan KERANGKA empat berkas sebuah modul feature dari kontrak:
//
//	register.<gen>   Register() -> <pkg>gen.Mount, store di-inject nil
//	handler.<gen>    impl StrictServerInterface; memetakan tipe generated <-> tipe internal
//	service.<gen>    delegasi tipis handler -> store
//	repository.<gen> interface `store`, seluruhnya bertipe INTERNAL
//
// Yang TIDAK dibangkitkan: lapis KUERI. Itu satu-satunya berkas yang menyimpan pengetahuan yang
// tidak ada di kontrak — SQL, join, dan terutama predikat penyewa (T-01: batas penyewa hidup di
// predikat kueri dan tidak bisa diturunkan dari kontrak). Karena itu ia ditulis tangan, dan
// sampai ia ada `Register` menyuntikkan `nil` sebagai store: modulnya kompilasi dan ikut boot,
// tapi setiap operasinya PANIC bila dipanggil. Itu keadaan yang disengaja dan TERLIHAT, bukan
// setengah jadi yang diam.
//
// # Sumber kebenaran: AST Go yang sudah digenerate, bukan bundel YAML
//
// Alat ini membaca berkas generated di `<genDir>/<pkg>` dengan go/parser, sama seperti gendto.
// Bukan bundel OpenAPI-nya. Alasannya sempit: nama tipe Go yang harus ditulis di keluaran
// (GetXParams, XCreateRequest, GetX200JSONResponse) adalah keputusan generator kode, bukan
// keputusan kontrak. Menurunkannya ulang dari YAML berarti menyalin aturan penamaan generator ke
// sini lalu berharap keduanya tidak pernah menyimpang. Membaca keluarannya membuat kelas itu
// tidak bisa ada.
//
// # Pembekuan: NAMA BERKAS yang jadi keadaannya, buku besar yang jadi klaimnya
//
// Sesudah kerangka ini dikawinkan dengan tangan (dependensi disuntik, validasi ditambahkan,
// perilaku per-operasi diperbaiki), modulnya TIDAK BOLEH digenerate ulang — generator tidak tahu
// dependensi apa yang disuntikkan atau proses apa yang ditambahkan di level service, dan menulis
// ulang berkasnya akan menghapusnya tanpa suara (B-03). `-freeze` menandai transisi itu dengan
// mengganti nama `<dasar><genSuffix>` -> `<dasar>.go`, dan sejak itu generator MENOLAK menyentuh
// modulnya.
//
// Keadaannya terbaca dari DISK — ada tidaknya berkas kerangka tanpa sufiks generated — bukan
// dari sebuah daftar. Daftar bisa menyimpang dari kenyataan; nama berkas tidak bisa. Buku besar
// modul terpasang adalah KLAIM atas keadaan itu, yang gate periksa dua arah (G-05).
//
//	genmodule [-config <jalur>] [-messages <dir>] -tag <TAG> -pkg <PKG> [-feature <DIR>] [-out <DIR>] [-apply] [-force]
//	genmodule [-config <jalur>] -pkg <PKG> [-feature <DIR>] -freeze [-apply]
