// modul adalah seluruh yang perlu diketahui untuk memancarkan berkas-berkasnya.
type modul struct {
	c       cfg.Config
	kat     cfg.Katalog
	tag     string // tag kontrak, mis. "buku-tamu"
	pkg     string // paket generated, mis. "bukutamu"
	feature string // direktori feature, mis. "tamu"
	alias   string // alias impor paket generated, mis. "bukutamugen"
	ops     []operasi
}

// operasi adalah satu metode StrictServerInterface, sudah diterjemahkan ke bentuk yang keempat
// template butuhkan.
type operasi struct {
	nama       string // metode Go, mis. "GetKeluargaById"
	rute       string // "GET /keluarga/{id}", dari komentar generator
	respons    string // tipe respons SUKSES, mis. "GetKeluarga200JSONResponse" — dari AST, bukan ditebak
	argumen    []argumen
	hasilWire  string // tipe field Data pada respons; "" bila responsnya tanpa Data
	hasil      konversi
	metaTipe   string // tipe field MetaData bila WAJIB; "" bila opsional/absen
	metaPag    string // tipe field Pagination DI DALAM metaTipe; "" bila metaTipe ""
	adaStatus  bool   // respons punya field Status DAN paket generated punya konstantanya
	adaMessage bool   // respons punya field Message
}

// argumen adalah satu parameter metode store/service, sudah dalam tipe INTERNAL.
type argumen struct {
	nama     string // "id", "params", "body"
	tipe     string // tipe internal, mis. "string", "dtoGetKeluargaParams"
	dariWire string // ekspresi Go yang mengubah request.<Field> jadi tipe internal
}

// konversi menerangkan cara mengubah hasil store (tipe internal) jadi field Data (tipe wire).
type konversi struct {
	tipeInternal string // tipe balik store, mis. "dtoKeluarga", "[]dtoKeluarga", "string"
	keWire       string // ekspresi Go; %s diisi nama variabel hasil
}

// ── Pembacaan ─────────────────────────────────────────────────────────────────

func baca(c cfg.Config, kat cfg.Katalog, akar, tag, pkg, feature string) (modul, error) {
	dirGen := filepath.Join(c.DirGen(akar), pkg)
	berkas, err := filepath.Glob(filepath.Join(dirGen, "*"+c.Go.GenSuffix))
	if err != nil {
		return modul{}, errors.New(kat.T("genmodule.gen_tak_terbaca",
			map[string]string{"jalur": dirGen, "sebab": err.Error(), "tag": tag, "pkg": pkg}))
	}
	if len(berkas) == 0 {
		return modul{}, errors.New(kat.T("genmodule.gen_tak_terbaca",
			map[string]string{"jalur": dirGen, "sebab": "0", "tag": tag, "pkg": pkg}))
	}
	sort.Strings(berkas)

	fset := token.NewFileSet()
	tipe := map[string]*ast.TypeSpec{} // nama tipe -> spec
	konst := map[string]bool{}         // nama konstanta
	var iface *ast.InterfaceType
	for _, f := range berkas {
		af, err := parser.ParseFile(fset, f, nil, parser.ParseComments)
		if err != nil {
			return modul{}, errors.New(kat.T("genmodule.gen_tak_terbaca",
				map[string]string{"jalur": f, "sebab": err.Error(), "tag": tag, "pkg": pkg}))
		}
		for _, d := range af.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, s := range gd.Specs {
				switch sp := s.(type) {
				case *ast.TypeSpec:
					tipe[sp.Name.Name] = sp
					if sp.Name.Name == "StrictServerInterface" {
						iface, _ = sp.Type.(*ast.InterfaceType)
					}
				case *ast.ValueSpec:
					for _, n := range sp.Names {
						konst[n.Name] = true
					}
				}
			}
		}
	}
	if iface == nil {
		return modul{}, errors.New(kat.T("genmodule.tanpa_strict_server",
			map[string]string{"jalur": dirGen}))
	}

	// Cermin privat yang gendto sudah bangkitkan: tipe wire X -> ada dtoX.
	cermin, err := bacaCermin(kat,
		filepath.Join(c.DirFeature(akar), feature, c.NamaBerkasGen("dto_"+pkg)))
	if err != nil {
		return modul{}, err
	}

	m := modul{c: c, kat: kat, tag: tag, pkg: pkg, feature: feature, alias: cfg.AliasGen(pkg)}
	for _, fld := range iface.Methods.List {
		if len(fld.Names) == 0 {
			continue
		}
		op, err := m.bacaOperasi(fld.Names[0].Name, fld, tipe, konst, cermin)
		if err != nil {
			return modul{}, err
		}
		m.ops = append(m.ops, op)
	}
	sort.Slice(m.ops, func(i, j int) bool { return m.ops[i].nama < m.ops[j].nama })
	return m, nil
}

// bacaCermin mengumpulkan nama tipe WIRE yang punya cermin internal, dari tanda tangan
// `func dto<X>FromWire(w <alias>.<X>) dto<X>` yang gendto pancarkan.
//
// Membaca fungsi KONVERTERNYA, bukan nama tipe `dtoX`: kehadiran konverter itulah yang
// menentukan apakah generator boleh menulis ekspresi konversi. Tipe cermin tanpa konverter akan
// menghasilkan Go yang tidak kompilasi, dan itu justru yang harus dihindari.
func bacaCermin(kat cfg.Katalog, jalur string) (map[string]bool, error) {
	out := map[string]bool{}
	src, err := os.ReadFile(jalur)
	if err != nil {
		return out, nil // gendto belum jalan untuk paket ini; seluruh tipe dianggap tak-bercermin
	}
	f, err := parser.ParseFile(token.NewFileSet(), jalur, src, 0)
	if err != nil {
		return nil, errors.New(kat.T("genmodule.cermin_tak_terurai",
			map[string]string{"jalur": jalur, "sebab": err.Error()}))
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Recv != nil {
			continue
		}
		n := fn.Name.Name
		if strings.HasPrefix(n, "dto") && strings.HasSuffix(n, "FromWire") {
			out[strings.TrimSuffix(strings.TrimPrefix(n, "dto"), "FromWire")] = true
		}
	}
	return out, nil
}

func (m modul) bacaOperasi(nama string, fld *ast.Field, tipe map[string]*ast.TypeSpec,
	konst, cermin map[string]bool) (operasi, error) {

	op := operasi{nama: nama, rute: ruteDariKomentar(fld)}

	// Argumen: dari field <nama>RequestObject, urutan apa adanya.
	if spec, ok := tipe[nama+"RequestObject"]; ok {
		if st, _ := spec.Type.(*ast.StructType); st != nil {
			for _, f := range st.Fields.List {
				if len(f.Names) == 0 {
					continue
				}
				op.argumen = append(op.argumen, m.bacaArgumen(f.Names[0].Name, f.Type, tipe, cermin))
			}
		}
	}

	// Tipe respons SUKSES dicari DI ANTARA tipe yang benar-benar ada, bukan dirakit dari
	// "<nama>200JSONResponse". Operasi yang suksesnya 201 atau 204 punya nama lain, dan versi
	// yang merakit namanya memancarkan `var out <alias>.<nama>200JSONResponse` atas tipe yang
	// tidak ada: Go yang SINTAKSISNYA sah, jadi gofmt lolos dan berkasnya mendarat di disk —
	// kegagalannya baru muncul saat build, jauh dari sebabnya.
	op.respons = namaRespons(nama, tipe)
	if op.respons == "" {
		return operasi{}, errors.New(m.kat.T("genmodule.tanpa_respons_sukses",
			map[string]string{"op": nama}))
	}
	st, _ := tipe[op.respons].Type.(*ast.StructType)
	if st == nil {
		return op, nil
	}
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			continue
		}
		switch f.Names[0].Name {
		case "Status":
			// Konstanta amplop diperiksa DUA arah: field-nya ada di respons ini, DAN paket
			// generated benar-benar mendeklarasikan konstantanya. Tag yang belum opt-in envelope
			// punya salah satunya saja, dan menulis keduanya menghasilkan Go yang tidak kompilasi.
			op.adaStatus = konst[konstStatusSukses]
		case "Message":
			op.adaMessage = true
		case "Data":
			// Alias diselesaikan di sisi respons juga, alasan yang sama dengan sisi argumen: nama
			// alias tidak dicerminkan gendto, jadi tanpa ini tipe wire bocor ke `store`.
			d := selesaikanAlias(f.Type, tipe)
			op.hasilWire = m.renderWire(d)
			op.hasil = m.keInternal(d, cermin)
		case "MetaData":
			// DUA bentuk metaData hidup berdampingan di kontrak, dan hanya satu yang urusan
			// lapis kueri:
			//
			//	MetaData SchemasMetaData   WAJIB — memuat `pagination`. Angkanya (total, page,
			//	                           totalPages) hanya diketahui kueri yang menghitungnya,
			//	                           jadi ia ikut nilai balik store.
			//	MetaData *MetaData         OPSIONAL — kanal metadata umum di samping payload.
			//	                           Tidak diturunkan dari kueri, dan memaksanya masuk tiap
			//	                           tanda tangan store hanya menambah nilai balik mati di
			//	                           mayoritas operasi.
			//
			// Bedanya terbaca dari POINTER-nya, bukan dari nama tipenya: generator memancarkan
			// field wajib sebagai nilai dan opsional sebagai pointer. Jadi aturan ini tetap benar
			// kalau kelak nama tipenya bergeser.
			if _, opsional := f.Type.(*ast.StarExpr); !opsional {
				pag, err := m.bacaTipePaginasi(f.Type, tipe, nama)
				if err != nil {
					return operasi{}, err
				}
				op.metaTipe = m.renderWire(f.Type)
				op.metaPag = pag
			}
		}
	}
	return op, nil
}

// bacaTipePaginasi mengembalikan tipe field `Pagination` DI DALAM metaData wajib, dialias paket
// generated (mis. "keluargagen.Pagination").
//
// Dibutuhkan karena metaData wajib TIDAK mengalir dari store sebagai tipe generated (itu
// melanggar B-01, lihat tandaTangan) — handler yang MENYUSUNNYA dari nilai paginasi platform,
// dan untuk menyusun ia perlu menyebut tipe field dalamnya.
//
// Bentuk yang tak terduga dihentikan NYARING, bukan ditebak: kalau kontrak kelak menambah field
// kedua di metaData wajib, keluaran yang ditebak akan kompilasi di sebagian tag dan gagal di
// sebagian lain — kegagalan yang muncul jauh dari sebabnya.
func (m modul) bacaTipePaginasi(e ast.Expr, tipe map[string]*ast.TypeSpec, op string) (string, error) {
	id, ok := e.(*ast.Ident)
	if !ok {
		return "", errors.New(m.kat.T("genmodule.meta_bukan_ident",
			map[string]string{"op": op, "bentuk": fmt.Sprintf("%T", e)}))
	}
	spec, ok := tipe[id.Name]
	if !ok {
		return "", errors.New(m.kat.T("genmodule.meta_tipe_hilang",
			map[string]string{"op": op, "tipe": id.Name}))
	}
	st, _ := spec.Type.(*ast.StructType)
	if st == nil || len(st.Fields.List) != 1 || len(st.Fields.List[0].Names) != 1 ||
		st.Fields.List[0].Names[0].Name != "Pagination" {
		return "", errors.New(m.kat.T("genmodule.meta_bentuk_lain",
			map[string]string{"op": op, "tipe": id.Name}))
	}
	return m.renderWire(st.Fields.List[0].Type), nil
}

// bacaArgumen menerjemahkan satu field RequestObject jadi parameter store bertipe internal.
func (m modul) bacaArgumen(nama string, e ast.Expr, tipe map[string]*ast.TypeSpec,
	cermin map[string]bool) argumen {

	src := "request." + nama
	lower := strings.ToLower(nama[:1]) + nama[1:]

	// `Body *<Op>JSONRequestBody`, dan JSONRequestBody itu ALIAS ke tipe skema sesungguhnya.
	// Aliasnya diselesaikan supaya cermin internalnya ketemu — gendto melewati nama
	// *JSONRequestBody sebagai plumbing, jadi mencarinya dengan nama itu selalu gagal.
	e = selesaikanAlias(e, tipe)

	// dariWire mengembalikan `src` apa adanya untuk tipe tak-bercermin — jadi kedua kasus
	// (bercermin / tidak) lewat jalur yang sama dan tidak bisa menyimpang.
	k := m.keInternal(e, cermin)
	return argumen{nama: lower, tipe: k.tipeInternal, dariWire: m.dariWire(e, cermin, src)}
}

// maksHop membatasi penelusuran rantai alias. Rantai alias melingkar tidak bisa ada dalam Go
// yang kompilasi, jadi batas ini bukan penanganan kasus nyata melainkan sabuk pengaman supaya
// masukan yang rusak berhenti dengan tipe apa adanya, bukan menggantung.
const maksHop = 16

// selesaikanAlias menelusuri rantai alias tipe sampai ke bentuk sesungguhnya.
//
// Perlu REKURSIF dan perlu menerima target apa pun, bukan cuma *ast.Ident — generator
// memancarkan rantai DUA HOP saat badan request-nya array inline:
//
//	type PostXJSONBody        = []XCreateRequestItem   // hop 2: target SLICE
//	type PostXJSONRequestBody = PostXJSONBody          // hop 1: target Ident
//
// Versi satu-hop/hanya-Ident berhenti di `PostXJSONBody`, yang tidak dicerminkan gendto,
// sehingga tipe WIRE bocor ke `store` — persis lapisan yang interface itu ada untuk
// menjauhkannya.
func selesaikanAlias(e ast.Expr, tipe map[string]*ast.TypeSpec) ast.Expr {
	switch t := e.(type) {
	case *ast.StarExpr:
		return &ast.StarExpr{X: selesaikanAlias(t.X, tipe)}
	case *ast.ArrayType:
		return &ast.ArrayType{Elt: selesaikanAlias(t.Elt, tipe)}
	case *ast.Ident:
		cur := e
		for hop := 0; hop < maksHop; hop++ {
			id, ok := cur.(*ast.Ident)
			if !ok {
				// Target bukan nama: telusuri ke dalamnya (mis. `[]XCreateRequestItem` yang
				// elemennya sendiri bisa alias) lalu selesai.
				return selesaikanAlias(cur, tipe)
			}
			sp, ada := tipe[id.Name]
			if !ada || !sp.Assign.IsValid() {
				return cur // tipe sungguhan, bukan alias — berhenti
			}
			cur = sp.Type
		}
		return cur
	}
	return e
}

// ── Terjemahan tipe ───────────────────────────────────────────────────────────

// renderWire menulis ekspresi tipe sebagaimana ia harus muncul DI LUAR paket generated: nama
// tipe milik paket itu diberi awalan alias, tipe bawaan tidak.
func (m modul) renderWire(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		if tipeBawaan[t.Name] {
			return t.Name
		}
		return m.alias + "." + t.Name
	case *ast.StarExpr:
		return "*" + m.renderWire(t.X)
	case *ast.ArrayType:
		return "[]" + m.renderWire(t.Elt)
	case *ast.MapType:
		return "map[" + m.renderWire(t.Key) + "]" + m.renderWire(t.Value)
	default:
		// mis. openapi_types.UUID / time.Time — sudah berkualifikasi, biarkan.
		return tulisEkspresi(e)
	}
}

// ── Konversi: rekursif atas bentuk tipe, bukan daftar kasus khusus ────────────
//
// Ketiga fungsi di bawah (tipeInternal, fnKeWire, fnDariWire) berjalan pada STRUKTUR tipenya,
// jadi `*[]T`, `[][]T`, dan `map[string][]T` ikut tertangani tanpa satu cabang pun ditambahkan.
// Bentuk sebelumnya menangani tepat tiga kasus dangkal — `T`, `[]T`, `*T` — dan `*[]T` (badan
// request array inline) jatuh ke cabang default: tipe wire bocor ke `store`, diam-diam, tanpa
// satu pun galat kompilasi. Kasus khusus yang dangkal selalu punya kasus keempat.

// tipeInternal menulis tipe yang dipakai `store`/`service`: cermin `dto*` di mana ada, tipe wire
// di mana tidak.
func (m modul) tipeInternal(e ast.Expr, cermin map[string]bool) string {
	switch t := e.(type) {
	case *ast.Ident:
		if cermin[t.Name] {
			return "dto" + t.Name
		}
		return m.renderWire(e)
	case *ast.ArrayType:
		return "[]" + m.tipeInternal(t.Elt, cermin)
	case *ast.StarExpr:
		return "*" + m.tipeInternal(t.X, cermin)
	case *ast.MapType:
		// Kunci map tidak pernah bercermin (kontrak hanya mengizinkan string), nilainya bisa.
		return "map[" + m.renderWire(t.Key) + "]" + m.tipeInternal(t.Value, cermin)
	default:
		return m.renderWire(e)
	}
}

// fnKeWire mengembalikan EKSPRESI FUNGSI Go yang mengubah nilai internal jadi nilai wire, atau
// "" bila tipenya sama di kedua sisi (tak perlu konversi).
func (m modul) fnKeWire(e ast.Expr, cermin map[string]bool) string {
	konv := m.c.PkgDtoconv()
	switch t := e.(type) {
	case *ast.Ident:
		if cermin[t.Name] {
			return fmt.Sprintf("func(v dto%s) %s.%s { return v.toWire() }", t.Name, m.alias, t.Name)
		}
	case *ast.ArrayType:
		if inner := m.fnKeWire(t.Elt, cermin); inner != "" {
			return fmt.Sprintf("func(s %s) %s { return %s.Slice(s, %s) }",
				m.tipeInternal(e, cermin), m.renderWire(e), konv, inner)
		}
	case *ast.StarExpr:
		if inner := m.fnKeWire(t.X, cermin); inner != "" {
			return fmt.Sprintf("func(p %s) %s { return %s.Ptr(p, %s) }",
				m.tipeInternal(e, cermin), m.renderWire(e), konv, inner)
		}
	case *ast.MapType:
		if inner := m.fnKeWire(t.Value, cermin); inner != "" {
			return fmt.Sprintf("func(m %s) %s { return %s.Map(m, %s) }",
				m.tipeInternal(e, cermin), m.renderWire(e), konv, inner)
		}
	}
	return ""
}

// fnDariWire adalah kebalikan fnKeWire: wire -> internal.
func (m modul) fnDariWire(e ast.Expr, cermin map[string]bool) string {
	konv := m.c.PkgDtoconv()
	switch t := e.(type) {
	case *ast.Ident:
		if cermin[t.Name] {
			return "dto" + t.Name + "FromWire" // gendto memancarkannya sebagai fungsi bernama
		}
	case *ast.ArrayType:
		if inner := m.fnDariWire(t.Elt, cermin); inner != "" {
			return fmt.Sprintf("func(s %s) %s { return %s.Slice(s, %s) }",
				m.renderWire(e), m.tipeInternal(e, cermin), konv, inner)
		}
	case *ast.StarExpr:
		if inner := m.fnDariWire(t.X, cermin); inner != "" {
			return fmt.Sprintf("func(p %s) %s { return %s.Ptr(p, %s) }",
				m.renderWire(e), m.tipeInternal(e, cermin), konv, inner)
		}
	case *ast.MapType:
		if inner := m.fnDariWire(t.Value, cermin); inner != "" {
			return fmt.Sprintf("func(m %s) %s { return %s.Map(m, %s) }",
				m.renderWire(e), m.tipeInternal(e, cermin), konv, inner)
		}
	}
	return ""
}

// keInternal memetakan tipe wire ke tipe INTERNAL yang store pakai, plus ekspresi yang mengubah
// nilai internal jadi nilai wire (%s = nama variabel).
//
// Ekspresi diterapkan LANGSUNG di titik pakai untuk bentuk tingkat-atas — `data.toWire()`,
// `<konv>.Slice(data, …)` — bukan lewat pembungkus fungsi, supaya keluarannya tetap terbaca
// seperti kode tulisan tangan. Pembungkus fnKeWire baru muncul di tingkat BERSARANG.
func (m modul) keInternal(e ast.Expr, cermin map[string]bool) konversi {
	k := konversi{tipeInternal: m.tipeInternal(e, cermin)}
	konv := m.c.PkgDtoconv()
	switch t := e.(type) {
	case *ast.Ident:
		if cermin[t.Name] {
			k.keWire = "%s.toWire()"
		}
	case *ast.ArrayType:
		if inner := m.fnKeWire(t.Elt, cermin); inner != "" {
			k.keWire = konv + ".Slice(%s, " + inner + ")"
		}
	case *ast.StarExpr:
		if inner := m.fnKeWire(t.X, cermin); inner != "" {
			k.keWire = konv + ".Ptr(%s, " + inner + ")"
		}
	case *ast.MapType:
		if inner := m.fnKeWire(t.Value, cermin); inner != "" {
			k.keWire = konv + ".Map(%s, " + inner + ")"
		}
	}
	return k
}

// dariWire menulis ekspresi yang mengubah nilai WIRE (`src`) jadi nilai internal — arah
// berlawanan dari konversi.keWire, dipakai untuk argumen masuk.
func (m modul) dariWire(e ast.Expr, cermin map[string]bool, src string) string {
	konv := m.c.PkgDtoconv()
	switch t := e.(type) {
	case *ast.Ident:
		if cermin[t.Name] {
			return fmt.Sprintf("dto%sFromWire(%s)", t.Name, src)
		}
	case *ast.ArrayType:
		if inner := m.fnDariWire(t.Elt, cermin); inner != "" {
			return fmt.Sprintf("%s.Slice(%s, %s)", konv, src, inner)
		}
	case *ast.StarExpr:
		if inner := m.fnDariWire(t.X, cermin); inner != "" {
			return fmt.Sprintf("%s.Ptr(%s, %s)", konv, src, inner)
		}
	case *ast.MapType:
		if inner := m.fnDariWire(t.Value, cermin); inner != "" {
			return fmt.Sprintf("%s.Map(%s, %s)", konv, src, inner)
		}
	}
	return src
}

func tulisEkspresi(e ast.Expr) string {
	var b bytes.Buffer
	_ = format.Node(&b, token.NewFileSet(), e)
	return b.String()
}

// ruteDariKomentar mengambil "GET /keluarga/{id}" dari komentar `// (GET /keluarga/{id})` yang
// generator tulis di atas tiap metode StrictServerInterface. Kosong bila tak ada — itu hanya
// memiskinkan komentar keluaran, tidak mengubah kodenya.
func ruteDariKomentar(fld *ast.Field) string {
	if fld.Doc == nil {
		return ""
	}
	for _, c := range fld.Doc.List {
		s := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if strings.HasPrefix(s, "(") && strings.HasSuffix(s, ")") {
			return s[1 : len(s)-1]
		}
	}
	return ""
}

