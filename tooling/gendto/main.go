// Alat gendto — bangkitkan cermin DTO PRIVAT per paket generated, plus konverter dua arah.
//
// Kenapa ada: modul bicara langsung ke tipe di paket generated di ribuan tempat. Saat nama
// tipe generated bergeser (mis. sebuah komponen dipindah ke berkas shared), yang patah bukan
// satu berkas seam melainkan setiap handler. Cermin privat memberi modul nama yang ia miliki
// sendiri; hanya berkas cermin yang menyebut paket generated.
//
// Alat ini membaca AST Go HASIL GENERATE, bukan YAML kontrak, dan itu disengaja: nama tipe Go
// adalah keputusan generator kode, bukan keputusan kontrak. Menurunkannya ulang dari YAML
// berarti menyalin aturan penamaan generator ke berkas ini lalu berharap keduanya tidak
// pernah menyimpang — dan saat menyimpang, yang patah adalah kompilasi setiap modul.
//
// Seluruh module path, direktori, sufiks berkas, nama paket konversi, dan pemetaan paket
// generated -> paket fitur datang dari standard.config.json serta buku besar modul terpasang.
// Tidak ada satu pun literal layout proyek di berkas ini.
//
//	go run ./gendto [-config <jalur>] [-messages <dir>] [-only <pkg>] [-apply]
